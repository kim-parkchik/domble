/**
 * 年ごとの、電子帳簿保存法への対応
 *  - 最初から厳密モードの帳簿：全部の年が対応
 *  - 通常 → 厳密に切り替えた帳簿：切り替えた年（strict_from_year）から対応。それより前の年は対応外
 *  - 通常モードの帳簿：全部の年が対応外
 * 対応外の年は、画面と印刷で目立たせる
 */
import type { Settings } from "./types";

export const isYearCompliant = (s: Pick<Settings, "e_book_mode" | "strict_from_year">, year: number) =>
  s.e_book_mode === "strict" && (s.strict_from_year === null || s.strict_from_year === undefined || year >= s.strict_from_year);

/** 途中から対応した帳簿の、対応前の年か（通常モードの帳簿の年は含めない） */
export const isBeforeStrict = (s: Pick<Settings, "e_book_mode" | "strict_from_year">, year: number) =>
  s.e_book_mode === "strict" && s.strict_from_year != null && year < s.strict_from_year;

